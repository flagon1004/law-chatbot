# app/services/cautions.py
"""분야별 주의사항.

AI가 법리를 한쪽으로 단정하기 쉬운 쟁점에 대해, 질문에 해당 단어가 있을 때만
프롬프트에 짧은 주의 문구를 덧붙인다. 조문·판례 번호를 새로 만들어 내지 않도록
'원칙'만 적고, 구체적 근거는 법제처에서 조회된 자료로만 제시하게 한다."""

CAUTIONS = [
    {
        # 금전 대여·차용 분쟁
        "triggers": ("빌려", "대여", "차용", "빌린", "갚", "계좌이체", "송금"),
        "text": (
            "금전 대여 분쟁에서는 계좌이체(송금) 사실만으로 '대여'가 당연히 인정되거나 "
            "추정된다고 단정하지 마세요. 송금은 증여·변제·투자·기존 채무 정산 등 다른 "
            "원인일 수 있어, 반환 약정(대여 합의)이 있었다는 점은 돈을 빌려줬다고 주장하는 "
            "쪽이 증명해야 하는 것이 일반적인 법리입니다. 계좌이체 내역은 '금전이 건너간 "
            "사실'의 증거이고, 대여 합의는 대화 내용·녹취·이자 지급·독촉에 대한 채무자의 "
            "반응 같은 정황으로 보강해야 한다는 점을 설명하세요. 이 원칙을 설명할 때 "
            "제공된 판례에 근거가 없다면 특정 판례번호를 만들어 인용하지 마세요."
        ),
    },
]


def matched_cautions(message: str) -> list:
    """질문에 트리거 단어가 하나라도 있는 분야의 주의 문구 목록."""
    return [c["text"] for c in CAUTIONS if any(t in message for t in c["triggers"])]
